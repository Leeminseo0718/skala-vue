// 위에서 못 찾으면 백의 자리로 큰 분류만 잡아 준다
const LABEL_BY_GROUP = {
  2: '천둥번개',
  3: '이슬비',
  5: '비',
  6: '눈',
  7: '안개',
  8: '흐림',
}

export function getWeatherLabel(conditionId) {
  if (LABEL_BY_ID[conditionId]) return LABEL_BY_ID[conditionId]
  // 520·521 같은 소나기 계열은 개별 정의 대신 여기서 걸린다
  if (conditionId >= 520 && conditionId <= 531) return '소나기'
  if (conditionId >= 620 && conditionId <= 622) return '소나기 눈'
  return LABEL_BY_GROUP[Math.floor(conditionId / 100)] ?? '정보 없음'
}

